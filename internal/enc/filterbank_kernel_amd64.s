// func subbandAVX2(x, window *[512]float64, matrixT *[64][32]float64, out *[32]float64)
// The partial sums accumulate x*window from zero in k order and each subband accumulates matrixT*y
// from zero in j order, multiply and add separate, the same per-term rounding as window, partialSums
// and matrixStep.
TEXT ·subbandAVX2(SB), 0, $512-32
	MOVQ x+0(FP), SI
	MOVQ window+8(FP), DX
	MOVQ matrixT+16(FP), R8
	MOVQ out+24(FP), DI
	XORQ AX, AX

partial:
	VXORPD  Y0, Y0, Y0
	VXORPD  Y1, Y1, Y1
	VXORPD  Y2, Y2, Y2
	VXORPD  Y3, Y3, Y3
	VMOVUPD 0(SI)(AX*1), Y4
	VMULPD  0(DX)(AX*1), Y4, Y4
	VADDPD  Y4, Y0, Y0
	VMOVUPD 32(SI)(AX*1), Y5
	VMULPD  32(DX)(AX*1), Y5, Y5
	VADDPD  Y5, Y1, Y1
	VMOVUPD 64(SI)(AX*1), Y6
	VMULPD  64(DX)(AX*1), Y6, Y6
	VADDPD  Y6, Y2, Y2
	VMOVUPD 96(SI)(AX*1), Y7
	VMULPD  96(DX)(AX*1), Y7, Y7
	VADDPD  Y7, Y3, Y3
	VMOVUPD 512(SI)(AX*1), Y4
	VMULPD  512(DX)(AX*1), Y4, Y4
	VADDPD  Y4, Y0, Y0
	VMOVUPD 544(SI)(AX*1), Y5
	VMULPD  544(DX)(AX*1), Y5, Y5
	VADDPD  Y5, Y1, Y1
	VMOVUPD 576(SI)(AX*1), Y6
	VMULPD  576(DX)(AX*1), Y6, Y6
	VADDPD  Y6, Y2, Y2
	VMOVUPD 608(SI)(AX*1), Y7
	VMULPD  608(DX)(AX*1), Y7, Y7
	VADDPD  Y7, Y3, Y3
	VMOVUPD 1024(SI)(AX*1), Y4
	VMULPD  1024(DX)(AX*1), Y4, Y4
	VADDPD  Y4, Y0, Y0
	VMOVUPD 1056(SI)(AX*1), Y5
	VMULPD  1056(DX)(AX*1), Y5, Y5
	VADDPD  Y5, Y1, Y1
	VMOVUPD 1088(SI)(AX*1), Y6
	VMULPD  1088(DX)(AX*1), Y6, Y6
	VADDPD  Y6, Y2, Y2
	VMOVUPD 1120(SI)(AX*1), Y7
	VMULPD  1120(DX)(AX*1), Y7, Y7
	VADDPD  Y7, Y3, Y3
	VMOVUPD 1536(SI)(AX*1), Y4
	VMULPD  1536(DX)(AX*1), Y4, Y4
	VADDPD  Y4, Y0, Y0
	VMOVUPD 1568(SI)(AX*1), Y5
	VMULPD  1568(DX)(AX*1), Y5, Y5
	VADDPD  Y5, Y1, Y1
	VMOVUPD 1600(SI)(AX*1), Y6
	VMULPD  1600(DX)(AX*1), Y6, Y6
	VADDPD  Y6, Y2, Y2
	VMOVUPD 1632(SI)(AX*1), Y7
	VMULPD  1632(DX)(AX*1), Y7, Y7
	VADDPD  Y7, Y3, Y3
	VMOVUPD 2048(SI)(AX*1), Y4
	VMULPD  2048(DX)(AX*1), Y4, Y4
	VADDPD  Y4, Y0, Y0
	VMOVUPD 2080(SI)(AX*1), Y5
	VMULPD  2080(DX)(AX*1), Y5, Y5
	VADDPD  Y5, Y1, Y1
	VMOVUPD 2112(SI)(AX*1), Y6
	VMULPD  2112(DX)(AX*1), Y6, Y6
	VADDPD  Y6, Y2, Y2
	VMOVUPD 2144(SI)(AX*1), Y7
	VMULPD  2144(DX)(AX*1), Y7, Y7
	VADDPD  Y7, Y3, Y3
	VMOVUPD 2560(SI)(AX*1), Y4
	VMULPD  2560(DX)(AX*1), Y4, Y4
	VADDPD  Y4, Y0, Y0
	VMOVUPD 2592(SI)(AX*1), Y5
	VMULPD  2592(DX)(AX*1), Y5, Y5
	VADDPD  Y5, Y1, Y1
	VMOVUPD 2624(SI)(AX*1), Y6
	VMULPD  2624(DX)(AX*1), Y6, Y6
	VADDPD  Y6, Y2, Y2
	VMOVUPD 2656(SI)(AX*1), Y7
	VMULPD  2656(DX)(AX*1), Y7, Y7
	VADDPD  Y7, Y3, Y3
	VMOVUPD 3072(SI)(AX*1), Y4
	VMULPD  3072(DX)(AX*1), Y4, Y4
	VADDPD  Y4, Y0, Y0
	VMOVUPD 3104(SI)(AX*1), Y5
	VMULPD  3104(DX)(AX*1), Y5, Y5
	VADDPD  Y5, Y1, Y1
	VMOVUPD 3136(SI)(AX*1), Y6
	VMULPD  3136(DX)(AX*1), Y6, Y6
	VADDPD  Y6, Y2, Y2
	VMOVUPD 3168(SI)(AX*1), Y7
	VMULPD  3168(DX)(AX*1), Y7, Y7
	VADDPD  Y7, Y3, Y3
	VMOVUPD 3584(SI)(AX*1), Y4
	VMULPD  3584(DX)(AX*1), Y4, Y4
	VADDPD  Y4, Y0, Y0
	VMOVUPD 3616(SI)(AX*1), Y5
	VMULPD  3616(DX)(AX*1), Y5, Y5
	VADDPD  Y5, Y1, Y1
	VMOVUPD 3648(SI)(AX*1), Y6
	VMULPD  3648(DX)(AX*1), Y6, Y6
	VADDPD  Y6, Y2, Y2
	VMOVUPD 3680(SI)(AX*1), Y7
	VMULPD  3680(DX)(AX*1), Y7, Y7
	VADDPD  Y7, Y3, Y3
	VMOVUPD Y0, 0(SP)(AX*1)
	VMOVUPD Y1, 32(SP)(AX*1)
	VMOVUPD Y2, 64(SP)(AX*1)
	VMOVUPD Y3, 96(SP)(AX*1)
	ADDQ    $128, AX
	CMPQ    AX, $512
	JLT     partial

	VXORPD Y0, Y0, Y0
	VXORPD Y1, Y1, Y1
	VXORPD Y2, Y2, Y2
	VXORPD Y3, Y3, Y3
	VXORPD Y4, Y4, Y4
	VXORPD Y5, Y5, Y5
	VXORPD Y6, Y6, Y6
	VXORPD Y7, Y7, Y7
	XORQ   AX, AX

matrix:
	VBROADCASTSD (SP)(AX*1), Y8
	VMULPD       0(R8), Y8, Y9
	VADDPD       Y9, Y0, Y0
	VMULPD       32(R8), Y8, Y10
	VADDPD       Y10, Y1, Y1
	VMULPD       64(R8), Y8, Y11
	VADDPD       Y11, Y2, Y2
	VMULPD       96(R8), Y8, Y12
	VADDPD       Y12, Y3, Y3
	VMULPD       128(R8), Y8, Y9
	VADDPD       Y9, Y4, Y4
	VMULPD       160(R8), Y8, Y10
	VADDPD       Y10, Y5, Y5
	VMULPD       192(R8), Y8, Y11
	VADDPD       Y11, Y6, Y6
	VMULPD       224(R8), Y8, Y12
	VADDPD       Y12, Y7, Y7
	ADDQ         $256, R8
	ADDQ         $8, AX
	CMPQ         AX, $512
	JLT          matrix

	VMOVUPD Y0, 0(DI)
	VMOVUPD Y1, 32(DI)
	VMOVUPD Y2, 64(DI)
	VMOVUPD Y3, 96(DI)
	VMOVUPD Y4, 128(DI)
	VMOVUPD Y5, 160(DI)
	VMOVUPD Y6, 192(DI)
	VMOVUPD Y7, 224(DI)
	VZEROUPPER
	RET
