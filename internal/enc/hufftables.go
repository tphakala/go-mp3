// Layer III Huffman encode tables, ISO/IEC 11172-3 Table B.7 (the
// big-values codebooks 1-31 and the two count1 "quad" codebooks A and B).
//
// This is an independent clean-room transcription: the tables were
// recovered by walking internal/dec's ISO-derived canonical Huffman trees
// (huffTabs / tab32Table / tab33Table, themselves ported from the
// CC0-licensed minimp3 reference and explicitly whitelisted by this
// project's provenance rules as a verification oracle for Table B.7,
// since that data IS the ISO table) bit by bit to recover the codeword and
// length for every (x, y) leaf, cross-checked against ISO Table B.7 values
// from memory for tables 1-3 (exact match) and re-verified end to end by
// TestEncHuffmanDecRoundTrip (internal/dec/encx_huffman_test.go), which
// decodes every table's every codeword with the decoder's independent ISO
// tables and requires the recovered magnitude and sign to match exactly.
// See PROVENANCE.md; no LAME, Shine, dist10, libmad, mpg123, FFmpeg, or
// Helix source was consulted.

// codeEntry is one Huffman codeword: the code bits (MSB-aligned to length)
// and the bit length. Transcribed from ISO/IEC 11172-3 Table B.7.
type codeEntry struct {
	code uint32
	len  uint8
}

// huffTable describes one big-values codebook: its (x, y) dimension, its
// linbits count (0 for non-escape tables), and the codeword for each
// (x, y) pair indexed x*dim+y.
type huffTable struct {
	dim     int // 2..16
	linbits int
	codes   []codeEntry
}

